/**
 * exporter.ts — Master export module for the Door Annotation Tool.
 *
 * Supports:
 * - YOLO Segmentation format (labels/*.txt + dataset.yaml)
 * - COCO JSON format
 * - BIM/IFC JSON format
 * - Label Check images (check/ folder with annotated overlays for visual QA)
 *
 * The `check/` folder contains PNG images with all annotations rendered
 * on top of the original floorplan so annotators can visually verify
 * label quality before starting YOLO training.
 */

import JSZip from 'jszip';
import type { Annotation, ClassDefinition, Point } from '../store/useStore';
import { isDoorTool } from '../store/useStore';
import type { DoorType } from '../types/door';
import { DOOR_TYPE_LABELS } from '../types/door';
import { generateLabelCheckImage } from './labelCheck';

// ─── Door class definitions (5 types) ───────────────────────────────────────
const DOOR_CLASSES: ClassDefinition[] = [
  { id: 0, name: 'single_door',   color: '#3b82f6' },
  { id: 1, name: 'double_door',   color: '#8b5cf6' },
  { id: 2, name: 'sliding_door',  color: '#06b6d4' },
  { id: 3, name: 'cavity_slider', color: '#f59e0b' },
  { id: 4, name: 'bi_fold',       color: '#10b981' },
];

/** Maps a DoorType to its YOLO class ID */
const doorTypeToClassId = (dt: DoorType): number => {
  switch (dt) {
    case 'single_door':   return 0;
    case 'double_door':   return 1;
    case 'sliding_door':  return 2;
    case 'cavity_slider': return 3;
    case 'bi_fold':       return 4;
    default:              return 0;
  }
};

// ─── YOLO Segmentation Export (with check/ folder) ──────────────────────────
export const exportYOLOSegmentation = async (
  annotations: Annotation[],
  imageSize: { width: number; height: number },
  imageName: string,
  classes: ClassDefinition[],
  sourceImage?: HTMLImageElement | null
) => {
  const zip = new JSZip();
  const labelsDir = zip.folder("labels");
  const checkDir = zip.folder("check");
  
  let labelContent = "";
  
  annotations.forEach(ann => {
    const polygon = ann.polygon || ann.geometry?.polygon;
    if (isDoorTool(ann.type) && polygon && polygon.length > 2) {
      // Determine class ID from door type
      const dt: DoorType = (ann.semantics?.type as DoorType) || 'single_door';
      const classId = doorTypeToClassId(dt);

      // Normalize polygon points to [0, 1]
      const normalized = polygon.map((p: Point) => ({
        x: Math.max(0, Math.min(1, p.x / imageSize.width)),
        y: Math.max(0, Math.min(1, p.y / imageSize.height))
      }));
      
      const pointsStr = normalized.map((p: Point) => `${p.x.toFixed(6)} ${p.y.toFixed(6)}`).join(" ");
      labelContent += `${classId} ${pointsStr}\n`;
    }
  });

  const baseName = imageName.split('.').slice(0, -1).join('.') || "floorplan";
  labelsDir?.file(`${baseName}.txt`, labelContent);

  // ── Generate check/ label visualization image ──
  if (sourceImage && checkDir) {
    try {
      const checkBlob = await generateLabelCheckImage(sourceImage, annotations);
      checkDir.file(`${baseName}_check.png`, checkBlob);
    } catch (err) {
      console.error('[exporter] Failed to generate label check image:', err);
    }
  }

  // ── Generate dataset.yaml with 5 door classes ──
  const allClasses = classes.length > 0 ? classes : DOOR_CLASSES;
  const yamlContent = `# EzeFloor Door Annotation Dataset
# Generated by DoorAnnotator PRO
# ${new Date().toISOString()}

path: ./dataset
train: images/train
val: images/val
test: images/test

nc: ${allClasses.length}

names:
${allClasses.map(c => `  ${c.id}: ${c.name}`).join("\n")}
`;
  zip.file("dataset.yaml", yamlContent);

  // ── Generate class summary info ──
  const doorAnns = annotations.filter(a => isDoorTool(a.type));
  const classCounts: Record<string, number> = {};
  doorAnns.forEach(ann => {
    const dt: DoorType = (ann.semantics?.type as DoorType) || 'single_door';
    classCounts[dt] = (classCounts[dt] || 0) + 1;
  });

  const summaryContent = `# Export Summary
# Date: ${new Date().toISOString()}
# Image: ${imageName} (${imageSize.width}x${imageSize.height})
# Total Annotations: ${doorAnns.length}
#
# Class Distribution:
${Object.entries(classCounts).map(([k, v]) => `#   ${k}: ${v}`).join('\n')}
#
# Files:
#   labels/${baseName}.txt  — YOLO segmentation labels
#   check/${baseName}_check.png — Visual label verification
#   dataset.yaml — Dataset configuration
`;
  zip.file("README.txt", summaryContent);

  const content = await zip.generateAsync({ type: "blob" });
  const url = URL.createObjectURL(content);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${baseName}_dataset_export.zip`;
  link.click();
  URL.revokeObjectURL(url);
};

// ─── COCO JSON Export ───────────────────────────────────────────────────────
export const exportCOCO = async (
  annotations: Annotation[],
  imageSize: { width: number; height: number },
  imageName: string,
  classes: ClassDefinition[]
) => {
  const allClasses = classes.length > 0 ? classes : DOOR_CLASSES;

  const coco = {
    info: {
      description: "EzeFloor Door Annotation Dataset",
      version: "2.0.0",
      year: new Date().getFullYear(),
      date_created: new Date().toISOString(),
    },
    images: [{
      id: 1,
      width: imageSize.width,
      height: imageSize.height,
      file_name: imageName
    }],
    annotations: annotations.map((ann, idx) => {
      const polygon = ann.polygon || ann.geometry?.polygon;
      if (isDoorTool(ann.type) && polygon && polygon.length > 2) {
        const dt: DoorType = (ann.semantics?.type as DoorType) || 'single_door';
        const classId = doorTypeToClassId(dt);
        const flatPolygon = polygon.flatMap((p: Point) => [p.x, p.y]);

        // Compute bounding box [x, y, w, h]
        const xs = polygon.map((p: Point) => p.x);
        const ys = polygon.map((p: Point) => p.y);
        const bx = Math.min(...xs);
        const by = Math.min(...ys);
        const bw = Math.max(...xs) - bx;
        const bh = Math.max(...ys) - by;

        return {
          id: idx + 1,
          image_id: 1,
          category_id: classId,
          segmentation: [flatPolygon],
          area: bw * bh,
          bbox: [bx, by, bw, bh],
          iscrowd: 0,
          attributes: {
            door_type: dt,
            hinge_side: ann.semantics?.hingeSide || 'unknown',
            swing: ann.semantics?.swing || 'unknown',
            width_px: ann.semantics?.width || 0,
          }
        };
      }
      return null;
    }).filter(Boolean) as any,
    categories: allClasses.map(c => ({
      id: c.id,
      name: c.name,
      supercategory: "building_element"
    }))
  };

  const blob = new Blob([JSON.stringify(coco, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = "annotations_coco.json";
  link.click();
  URL.revokeObjectURL(url);
};
